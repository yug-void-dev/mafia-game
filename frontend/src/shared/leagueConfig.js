/**
 * Returns the League object corresponding to a player's trophy count.
 * @param {number} trophies
 * @returns {object} League tier object
 */
export function getLeagueByTrophies(trophies = 0) {
  const count = Math.max(0, Number(trophies) || 0);
  const matched = LEAGUE_TIERS.find((tier) => count >= tier.min && count <= tier.max);
  return matched || LEAGUE_TIERS[0];
}
